_current = "pt"


def set_language(code: str | None) -> str:
    global _current
    _current = code if code in TRANSLATIONS else "pt"
    return _current


def get_language() -> str:
    return _current


def language_name(code: str | None = None) -> str:
    return LANGUAGES.get(code or _current, LANGUAGES["pt"])


def tr(key: str, **kwargs) -> str:
    text = TRANSLATIONS.get(_current, {}).get(key)
    if text is None:
        text = TRANSLATIONS["pt"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
